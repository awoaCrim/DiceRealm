namespace DiceRealm.Server.Domain;

// A level-1 acquisition draft. These are choices, never client-supplied derived statistics.
// Missing choices remain missing in drafts; evaluation never selects replacements.
public sealed record CharacterBuild
{
    public string Ruleset { get; init; } = "dnd2024";
    public string Revision { get; init; } = BuildCatalog.Revision;
    public string ClassId { get; init; } = "";
    public string SpeciesId { get; init; } = "";
    public string BackgroundId { get; init; } = "";
    public string AbilityMethod { get; init; } = "standard";
    public int[] BaseScores { get; init; } = [];
    public int[] BackgroundBonuses { get; init; } = [];
    public string[] ClassSkills { get; init; } = [];
    public string[] Expertise { get; init; } = [];
    public BuildSelection[] Selections { get; init; } = [];
    public string[] Cantrips { get; init; } = [];
    public string[] PreparedSpells { get; init; } = [];
    public string[] Spellbook { get; init; } = [];
    public string ClassEquipment { get; init; } = "";
    public string BackgroundEquipment { get; init; } = "";
    public BuildPurchase[] Purchases { get; init; } = [];
    public string[] Equipped { get; init; } = [];
    public BuildIdentity Identity { get; init; } = new();
}
public sealed record BuildIdentity
{
    public string Name { get; init; } = "";
    public string Pronouns { get; init; } = "";
    public string Appearance { get; init; } = "";
    public string Personality { get; init; } = "";
    public string Backstory { get; init; } = "";
    public string Alignment { get; init; } = "neutral";
}
public sealed record BuildSelection(string Key, string[] Values);
public sealed record BuildPurchase(string Id, int Quantity);
public sealed record BuildIssue(string Step, string Code, string Message, string Key = "");
public sealed record BuildStep(string Id, bool Complete, int IssueCount);
public sealed record BuildOption(string Id, string Label, string Description = "");
public sealed record BuildGroup(string Key, string Step, string Label, int Count, BuildOption[] Options, string[] Selected, string[] DependsOn, bool Complete);
public sealed record BuildSpellGrant(string Id, string Ability, string Source, string Mode, int FreeUses = 0, int AttackBonus = 0, int SaveDc = 0);
public sealed record BuildSaveValue(string Ability, int Modifier, bool Proficient);
public sealed record BuildSkillValue(string Id, string Name, string Ability, int Modifier, bool Proficient, bool Expertise);
public sealed record BuildMechanics(int HitDie, int Speed, string Size, string[] Saves, string[] ArmorTraining, string[] WeaponTraining,
    string[] Tools, string[] Languages, string[] Feats, string[] Masteries, string[] Resistances, BuildSpellGrant[] SpellGrants,
    BuildSkillValue[] Skills, int InitiativeBonus, int PassivePerception, int CurrencyCp, bool AutomatedCombat, BuildSaveValue[] SavingThrows);
public sealed record BuildEvaluation(string Fingerprint, bool CanCreate, BuildIssue[] Issues, BuildStep[] Steps, BuildGroup[] Groups,
    Character? Character, string[] Notices);
public sealed record EvaluateBuildRequest(CharacterBuild Build);

// Compact source metadata, generated by scripts/build_creation_catalog.py. No rulebook prose.
public sealed record BuildCatalogData(string Ruleset, string Source, string Revision, int SchemaVersion, int Level,
    string[] Abilities, int[] StandardArray, int[] PointCosts, int PointBudget, BuildSkill[] Skills,
    BuildClass[] Classes, BuildSpecies[] Species, BuildBackground[] Backgrounds, BuildFeat[] Feats,
    BuildLanguage[] Languages, BuildSpell[] Spells, BuildEquipment[] Equipment, BuildOption[] Alignments);
public sealed record BuildSkill(string Id, string Name, string Ability);
public sealed record BuildPool(int Count, string[] Options, bool MatchTraining = false);
public sealed record BuildTools(string[] Fixed, BuildPool[] Choices);
public sealed record BuildEquipmentPlan(string Id, BuildPurchase[] Items, int Copper, BuildPool[] Choices);
public sealed record BuildClass(string Id, string Name, string Label, int HitDie, string[] Saves, string[] Skills, int SkillCount,
    string[] Armor, string[] Weapons, BuildTools Tools, string[] Features, string SpellAbility,
    int Cantrips, int Prepared, int Spellbook, int Slots, bool PactMagic, string[] AutomaticSpells, BuildEquipmentPlan[] Equipment);
public sealed record BuildSpecies(string Id, string Name, string[] Sizes, int Speed, string[] Resistances, string[] Features);
public sealed record BuildBackground(string Id, string Name, string[] Abilities, string[] Skills, string Feat,
    string SpellClass, BuildTools Tools, BuildEquipmentPlan[] Equipment);
public sealed record BuildFeat(string Id, string Name, string Category, bool Repeatable, BuildTools Tools);
public sealed record BuildLanguage(string Id, string Name, string Kind);
public sealed record BuildSpell(string Id, string Name, int Level, string[] Classes, string School);
public sealed record BuildEquipment(string Id, string Name, string Kind, int? Price, int ArmorClass, int Strength,
    bool StealthDisadvantage, string WeaponCategory, string Damage, string[] Properties, string[] Mastery, string VersatileDamage = "",
    decimal? WeightPounds = null)
{ public bool HasPrice => Price is not null; }
